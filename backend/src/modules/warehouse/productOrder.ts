/** В базе у части артикулов пробел на конце, а регистр в разных местах разный. */
const skuKey = (sku: string) => sku.trim().toLowerCase();

const rankBySku = new Map(REPORT_ORDER_SKUS.map((sku, i) => [skuKey(sku), i]));

/** Ставит товары в порядок отчёта; остальные — в конец, сохраняя их взаимный порядок. */
export function sortByReportOrder<T extends { sku: string }>(products: T[]): T[] {
  const rank = (p: T) => rankBySku.get(skuKey(p.sku)) ?? REPORT_ORDER_SKUS.length;
  return [...products].sort((a, b) => rank(a) - rank(b));
}
