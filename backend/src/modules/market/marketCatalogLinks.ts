/** Артикулы в каталоге встречаются с лишними пробелами по краям — сравниваем нормализованно. */
export const normalizeSku = (sku: string) => sku.trim().toLowerCase();

export type OurPriceResolution = {
  price: number;
  /** true — цена из каталога CRM; false — из прайса (связи нет или у товаров нет цены). */
  fromCatalog: boolean;
  /** Разброс цен, если строка покрывает несколько позиций каталога с разной ценой. */
  range: [number, number] | null;
};

export function resolveOurPrice(
  ourProduct: string,
  fallback: number,
  priceBySku: Map<string, number>,
): OurPriceResolution {
  const link = CATALOG_LINKS[ourProduct];
  if (!link) return { price: fallback, fromCatalog: false, range: null };

  const perUnit = link.perUnit ?? 1;
  const prices = link.skus
    .map((sku) => priceBySku.get(normalizeSku(sku)))
    .filter((p): p is number => p !== undefined)
    .map((p) => p * perUnit);
  if (!prices.length) return { price: fallback, fromCatalog: false, range: null };

  // Самая частая цена; при равенстве частот — меньшая.
  const freq = new Map<number, number>();
  for (const p of prices) freq.set(p, (freq.get(p) ?? 0) + 1);
  const price = [...freq.entries()].sort((a, b) => b[1] - a[1] || a[0] - b[0])[0][0];
  const min = Math.min(...prices);
  const max = Math.max(...prices);
  return { price, fromCatalog: true, range: min !== max ? [min, max] : null };
}
