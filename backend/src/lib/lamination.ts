/**
 * Ламинационная плёнка продаётся по весу (кг), но выдаётся со склада рулонами —
 * поэтому у неё второй, параллельный остаток `Product.rollStock`, который списывается
 * вместе с килограммами при закрытии сделки.
 *
 * Каноническое место хранения количества рулонов — числовое поле `DealItem.rollCount`.
 * Разбор из текста комментария оставлен ТОЛЬКО как совместимость с позициями,
 * созданными до появления этого поля: раньше менеджер вводил рулоны в отдельный
 * инпут, а тот записывал их в свободный комментарий строкой «N рул.».
 */

export const LAMINATION_CATEGORY = 'Ламинационная пленка';

/**
 * Товар с рулонным учётом: категория ламинации И заведённый второй остаток.
 *
 * `rollStock === null` означает «рулоны у этого товара не считаем вообще» — в каталоге
 * такие в категории есть (напр. фасованная «ламинация» в пачках). Требовать для них
 * кол-во рулонов нельзя: списывать его всё равно некуда.
 */
export function isRollTrackedProduct(
  product: { category: string | null; rollStock?: unknown } | null | undefined,
): boolean {
  return !!product && product.category === LAMINATION_CATEGORY && product.rollStock != null;
}

/**
 * Достаёт количество рулонов из легаси-комментария позиции.
 *
 * Число обязано стоять В НАЧАЛЕ строки — ровно в том формате, который писал инпут
 * («N рул.»). Раньше регулярка была не заякорена и брала первое число откуда угодно,
 * из-за чего комментарий-пояснение вроде «заменили на 17 микрон» или «со 2 склада»
 * молча списывал со склада 17 или 2 рулона. Пояснение, начинающееся не с цифры,
 * теперь корректно даёт null — количество рулонов неизвестно.
 */
export function parseRollCountFromComment(comment: string | null | undefined): number | null {
  const m = String(comment ?? '').match(/^\s*(\d+(?:[.,]\d+)?)/);
  if (!m) return null;
  const value = parseFloat(m[1].replace(',', '.'));
  return Number.isFinite(value) && value > 0 ? value : null;
}
